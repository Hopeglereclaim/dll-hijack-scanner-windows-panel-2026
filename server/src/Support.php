<?php
declare(strict_types=1);

namespace DllHijackScannerWindows\Server;

final class Support
{
    public static function slug(string $value): string
    {
        $value = strtolower(trim($value));
        $value = preg_replace('/[^a-z0-9]+/', '-', $value) ?? '';
        return trim($value, '-');
    }
}
